#!/usr/bin/env python3
"""Regenerate app/flows/index.js — the list of flow files the app loads.
Run after adding a flow file, and after a merge (it never needs hand-editing, so it can't really conflict:
if git reports a conflict in it, just re-run this script).   python3 -I scripts/manifest.py"""
import pathlib
ROOT = pathlib.Path(__file__).resolve().parent.parent
flows = sorted(p.name for p in (ROOT / 'app/flows').glob('*.js') if p.name != 'index.js')
lines = ['/* GENERATED by scripts/manifest.py — do not edit. Loads every flow file in app/flows/, in name order. */',
         'window.FLOWS = window.FLOWS || [];',
         'window.FLOW_FILES = ' + repr(flows).replace("'", '"') + ';',
         'window.FLOW_FILES.forEach(f => document.write(\'<script src="app/flows/\' + f + \'?v=\' + (window.APP_V || Date.now()) + \'"><\\/script>\'));', '']
(ROOT / 'app/flows/index.js').write_text('\n'.join(lines), encoding='utf-8')
print(f'app/flows/index.js: {len(flows)} flow file(s)')
