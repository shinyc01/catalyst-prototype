const Upper = ({ children }) => <h3 className="t-heading-h3-medium" style={{ margin: 0 }}>{children}</h3>;   // rule 2.4: page section title (was grey Label in Figma; rule wins)
const TIP = {                                                                           // label tooltips (Figma dev notes)
  CPV: 'What the investment costs in today’s money.', 'V/C': 'Value generated per $1K of investment — higher means more value for the cost.',
  'Health index': 'How worn out the asset is, scored 0–10 (10 = like new).', Risk: 'Expected cost of failure, adjusted for how likely the asset is to fail.',
  'Forecast vs constraint': 'Expected spending against the available budget.', 'Total value': 'Total value generated by the investments.',
};
const tipLabel = l => TIP[l] ? <Tooltip content={TIP[l]}><span>{l}</span></Tooltip> : l;
const Trunc = ({ text }) => <Tooltip content={text}><span className="cmd-trunc">{text}</span></Tooltip>;
const fmtDay = d => d.toLocaleDateString('en-US', { month: 'short', day: 'numeric' });
const iso = d => `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`;
const TONE_COLOR = { danger: 'var(--background-system-danger)', warning: 'var(--background-system-warning)', info: 'var(--background-system-info)', purple: 'var(--background-solid-accent-purple)' };
const SORTS = [{ value: 'urgency', label: 'Sort by urgency' }, { value: 'date', label: 'Sort by date' }, { value: 'source', label: 'Sort by source' }, { value: 'collaborator', label: 'Sort by collaborator' }];
const DATE_PRESETS = [['year', 'Last year', 365], ['month', 'Last month', 31], ['week', 'Last 7 days', 7], ['day', 'Last day', 1], ['custom', 'Custom range']];

// Row wrapper: hover shows the drag handle (and the ⋮ menu on decisions); rows can be dragged to re-rank — not in DS
function RowShell({ id, children, menu, drag, setDrag, onDropOn, featured, noDrag }) {
  return (
    <NDS label={menu ? 'Drag to re-rank + card menu' : 'Drag to re-rank'} className={`cmd-row${drag === id ? ' dragging' : ''}${featured ? ' featured' : ''}`}
      style={{}} >
      <div draggable={!noDrag} onDragStart={e => { setDrag?.(id); e.dataTransfer.effectAllowed = 'move'; }} onDragEnd={() => setDrag?.(null)}
        onDragOver={e => { if (drag && drag !== id) e.preventDefault(); }} onDrop={e => { e.preventDefault(); onDropOn?.(id); }}>
        {!noDrag && <span className="cmd-handle" aria-hidden="true"><Icon name="system-drag-and-drop" size={16} /></span>}
        {children}
        {menu && <div className="cmd-kebab"><Menu more items={menu} label="Card actions" /></div>}
      </div>
    </NDS>
  );
}

function Command({ navBar, lenses, persona, onOpen }) {
  const P = PERSONAS[persona], C = COMMAND[persona] || COMMAND.owner;   // personas without their own Command content (CX Consultant) see the Investment Owner's [Assumed]
  const [tab, setTab] = useState('decisions');
  const [prio, setPrio] = useState('critical');
  const [order, setOrder] = usePersisted(`cmd.${persona}.order`, C.decisions.map(d => d.id));
  const [hidden, setHidden] = usePersisted(`cmd.${persona}.hidden`, {});                                      // id → 'snoozed' | 'archived'
  const [archOpen, setArchOpen] = useState(false);
  const [sort, setSort] = useState('urgency');
  const [chip, setChip] = useState({ date: 'month', source: 'Explore', collaborator: null });
  const [range, setRange] = useState(null);
  const [drag, setDrag] = useState(null);
  const [notified, setNotified] = usePersisted(`cmd.${persona}.notified`, {});
  const [events, setEvents] = usePersisted(`cmd.${persona}.events`, BASE_EVENTS);
  const [addOpen, setAddOpen] = useState(false);
  const [day, setDay] = useState(null);
  const byId = id => C.decisions.find(d => d.id === id);

  // ---- decisions list: order (drag) → hide snoozed/archived → filter by the active sort's chip
  const collaborators = [...new Set(C.decisions.map(d => d.collaborator))];
  const chipCol = chip.collaborator || collaborators[0];
  let list = order.map(byId).filter(d => !hidden[d.id]);
  if (sort === 'urgency') list = list.filter(d => d.priority === prio);
  if (sort === 'date') {
    if (chip.date === 'custom' && range?.start) list = list.filter(d => d.added >= range.start && d.added <= (range.end || range.start));
    else if (chip.date !== 'custom') { const days = DATE_PRESETS.find(p => p[0] === chip.date)[2]; list = list.filter(d => (STORY_DATE - d.added) / 864e5 <= days); }
    list = [...list].sort((a, b) => b.added - a.added);
  }
  if (sort === 'source') list = list.filter(d => d.badge === chip.source);
  if (sort === 'collaborator') list = list.filter(d => d.collaborator === chipCol);
  const archived = order.map(byId).filter(d => hidden[d.id] === 'archived');

  const dropOn = target => { if (!drag || drag === target) return; setOrder(o => { const a = o.filter(x => x !== drag); a.splice(a.indexOf(target), 0, drag); return a; }); setDrag(null); };
  const hide = (d, how) => {
    setHidden(h => ({ ...h, [d.id]: how }));
    const undo = () => setHidden(h => { const n = { ...h }; delete n[d.id]; return n; });
    toast({ title: how === 'snoozed' ? 'Decision snoozed for 7 days' : 'Decision archived', primaryAction: { label: 'Undo', iconLeft: 'arrow-back-up', onClick: undo }, duration: 5000 });
  };
  const unhide = d => setHidden(h => { const n = { ...h }; delete n[d.id]; return n; });

  const metricsOf = d => C.metrics === 'cpv' ? [{ value: fmtMoney(d.cpv), label: tipLabel('CPV') }, { value: vcLabel(d.vc), label: tipLabel('V/C') }]
    : C.metrics === 'hi' ? [{ value: d.hi, label: tipLabel('Health index') }, { value: d.risk, label: tipLabel('Risk') }]
    : [{ value: d.fvc, label: tipLabel('Forecast vs constraint') }, { value: d.value, label: tipLabel('Total value') }];
  const mapMedia = <NDS label="Live map" className="fill"><MapView labels={false} lenses={lenses} year={END} interactive={false} /></NDS>;
  const decisionCard = (d, i, opts = {}) => (
    <RowShell key={d.id} id={d.id} drag={drag} setDrag={setDrag} onDropOn={dropOn} featured={i === 0 && !opts.archived} noDrag={opts.archived}
      menu={opts.archived ? [{ label: 'Remind me later', icon: 'system-clock-time', onClick: () => { unhide(d); hide(d, 'snoozed'); } }, { label: 'Unarchive', icon: 'chat-archive', onClick: () => unhide(d) }]
        : [{ label: 'Remind me later', icon: 'system-clock-time', onClick: () => hide(d, 'snoozed') }, { label: 'Archive', icon: 'chat-archive', onClick: () => hide(d, 'archived') }]}>
      <HomeRowCard type={i === 0 && !opts.archived ? 'primary' : 'secondary'} rank={opts.archived ? undefined : i + 1} title={d.title} badge={d.badge}
        data-card={d.id} openLabel={d.verb} description={<Trunc text={d.description} />} metrics={metricsOf(d)} onOpen={() => onOpen(d)}
        media={i === 0 && !opts.archived && d.id === 'cluster' ? mapMedia : undefined} />
    </RowShell>
  );

  // ---- tabs (counts = what's in each list; hide My works when empty, per the dev note)
  const tabs = [
    C.works.length && { value: 'works', label: 'My works', count: C.works.length },
    { value: 'decisions', label: 'Decisions', count: order.filter(id => !hidden[id]).length },
    { value: 'conversations', label: 'Conversations', count: C.convos.length },
    { value: 'following', label: 'Following', count: C.following.length },
  ].filter(Boolean);
  const section = { works: 'Where You Left Off', decisions: 'Decisions to Review', conversations: 'Responses to Review', following: C.followTitle }[tab];

  // ---- the chips next to the section title follow the chosen sort
  const chipRow = sort === 'urgency' ? <SegmentedControl size="s" value={prio} onChange={setPrio} options={[{ value: 'normal', label: 'Normal' }, { value: 'high', label: 'High' }, { value: 'critical', label: 'Critical' }]} />
    : sort === 'date' ? <SegmentedControl size="s" value={chip.date} onChange={v => setChip(c => ({ ...c, date: v }))} options={DATE_PRESETS.map(([value, label]) => ({ value, label }))} />
    : sort === 'source' ? <SegmentedControl size="s" value={chip.source} onChange={v => setChip(c => ({ ...c, source: v }))} options={['Value', 'Results', 'Plan', 'Build', 'Explore'].map(v => ({ value: v, label: v }))} />
    : <SegmentedControl size="s" value={chipCol} onChange={v => setChip(c => ({ ...c, collaborator: v }))} options={collaborators.map(p => ({ value: p, label: short(p).replace('. ', '.') }))} />;
  const filterMenu = <Menu label="Sort" items={SORTS.map(s => ({ label: s.label, selected: sort === s.value, onClick: () => setSort(s.value) }))}
    trigger={<IconButton icon="system-filter-settings" type="ghost" size="s" label="Sort and filter" />} />;

  // ---- calendar
  const evByDay = events.reduce((m, e) => { (m[e.date] = m[e.date] || []).push(EVENT_TYPES[e.type].tone); return m; }, {});
  const dayEvents = day ? events.filter(e => e.date === iso(day)) : [];
  const stat = (v, l, style) => <div style={{ position: 'absolute', textAlign: 'center', ...style }}><div className="t-label-l-medium">{v}</div><div className="t-body-m-regular muted">{l}</div></div>;

  return (
    <AppShell navBar={navBar} bottom={<BottomSheet prompts={['Why is Alpine Meadows #1?', 'Brief me']} onPrompt={p => toast({ title: `Cooper: ${p}` })} />}>
      <div className="page"><div className="ifs-grid">
        <div className="page-col ifs-span-rest">
          <PageTop eyebrow title={`Welcome back, ${P.first}.`} description="2.8M simulations completed while you were away. Here are the items that require your input and attention right now."
            style={{ gap: 'var(--space-300)' }} tabs={{ items: tabs, value: tab, onChange: setTab }} search={{ placeholder: 'Ask anything about your work', suggestions: ['Why is Alpine Meadows #1?', 'What changed since Friday?'] }} />
          <Stack gap="400">
            <Inline justify="between" gap="300" align="center" style={{ minHeight: 'var(--size-28)' }}>
              <Upper>{section}</Upper>
              {tab === 'decisions' && <Inline gap="300" align="center">
                {chipRow}
                {sort === 'date' && chip.date === 'custom' && <div style={{ width: 'var(--proto-picker-w)' }}><DatePicker size="s" range showApply value={range} onChange={setRange} defaultOpen={!range} placeholder="Select a date range"
                  today={STORY_DATE} format={d => d.toLocaleDateString('en-US', { month: 'short', day: 'numeric', year: 'numeric' })} /></div>}
                <span className="cmd-divider" aria-hidden="true" />
                {filterMenu}
              </Inline>}
            </Inline>

            {tab === 'decisions' && <Stack gap="200">
              {list.map((d, i) => decisionCard(d, i))}
              {!list.length && <EmptyState cause="no-results" size="section" heading="No Decisions Match Your Filters" body="Try a different filter, or open Archived to see hidden items." />}
              {archived.length > 0 && <>
                <NDS label="Archived section header" className="cmd-archived row click" style={{}}>
                  <div className="row" style={{ gap: 'var(--space-200)', flex: 1 }} onClick={() => setArchOpen(o => !o)} role="button" tabIndex={0} aria-expanded={archOpen}>
                    <Icon name={archOpen ? 'arrow-caret-down-filled' : 'arrow-caret-right-filled'} size={16} />
                    <Icon name="chat-archive" size={16} /><span className="t-label-m-medium">Archived</span>
                  </div>
                  <Badge size="s" color="white">{archived.length}</Badge>
                </NDS>
                {archOpen && archived.map(d => decisionCard(d, 1, { archived: true }))}
              </>}
            </Stack>}

            {tab === 'works' && <Stack gap="200">
              {C.works.map((w, i) => (
                <RowShell key={w.id} id={w.id}>
                  <HomeRowCard type={w.featured ? 'primary' : 'secondary'} rank={i + 1} title={w.title} badge={w.badge} onOpen={() => onOpen(w)}
                    description={<span className="row" style={{ gap: 'var(--space-100)' }}><Icon name="system-clock-time" size={16} />{w.when}</span>}
                    media={w.featured ? mapMedia : undefined}
                    metrics={w.featured ? [{ value: <span className="row" style={{ gap: 'var(--space-200)' }}>{w.status === 'Updated' ? <Indicator type="blue">Updated</Indicator> : <span>Draft</span>}<span className="t-body-m-regular">{w.note}</span></span>, label: '' }]
                      : [{ value: w.status === 'Updated' ? <Indicator type="blue">Updated</Indicator> : 'Draft', label: '' }, { value: <span className="t-body-m-regular cmd-note">{w.note}</span>, label: '' }]} />
                </RowShell>))}
            </Stack>}

            {tab === 'conversations' && <Stack gap="200">
              {C.convos.map((c, i) => { const p = PEOPLE[c.person], n = notified[c.id]; return (
                <RowShell key={c.id} id={c.id} menu={c.status === 'Wait for reply' ? [n ? { label: `Reminded ${n}`, disabled: true } : { label: `Remind ${p.name}`, icon: 'system-notification', onClick: () => { setNotified(x => ({ ...x, [c.id]: fmtDay(STORY_DATE) })); toast({ title: `Reminder sent to ${p.name}`, description: 'Added to their Conversations list', duration: 5000 }); } }] : undefined}>
                  {/* Figma response card = the kit HomeRowCard (secondary): rank, person, title, their message, status tag; the arrow opens where it was said.
                      Remind (Wait for reply) moves to the card's ⋮ menu, since the card has one action (rule 7.9: one of each) */}
                  <HomeRowCard type="secondary" rank={i + 1} title={c.title} collaboration={{ initials: p.initials, type: p.type }}
                    description={`${p.role} · ${c.message}${n ? ` · Last notified ${n}` : ''}`} badge={c.status === 'mention' ? '@ mention' : c.status}
                    onOpen={() => onOpen(c)} openLabel="Open where the comment was made" />
                </RowShell>); })}
            </Stack>}

            {tab === 'following' && <Stack gap="200">
              {C.following.map((f, i) => (
                <RowShell key={f.id} id={f.id}>
                  <HomeRowCard type="secondary" rank={i + 1} title={f.title} description={<Trunc text={f.full || f.description} />}
                    metrics={f.metrics.map(([value, label]) => ({ value, label: tipLabel(label) }))} onOpen={() => onOpen(f)} />
                </RowShell>))}
            </Stack>}
          </Stack>
        </div>

        <div className="page-col cmd-right ifs-span-panel">
          <NDS label="Cooper’s work results gauge" className="box" style={{ height: 'var(--proto-gauge-h)', overflow: 'hidden' }}>
            <span className="t-heading-h4-semibold">Cooper’s Work Results</span>
            <div aria-hidden="true" style={{ position: 'absolute', left: '50%', top: 'var(--proto-gauge-top)', width: 'var(--proto-gauge-ring)', height: 'var(--proto-gauge-ring)', marginLeft: 'calc(-1 * var(--space-1100))', borderRadius: '50%', boxShadow: 'inset 0 0 0 var(--border-widths-border-100) var(--border-medium)', background: 'radial-gradient(circle at 50% 30%, var(--background-elevation-1-tertiary), transparent 70%)' }} />
            {stat('66%', 'Automation', { left: 0, right: 0, top: 'var(--size-56)' })}
            {stat('12', 'Portfolio changes', { left: 'var(--space-400)', top: 'calc(26 * var(--proto-unit))' })}
            {stat('12%', 'Risk reduction', { right: 'var(--space-400)', top: 'calc(26 * var(--proto-unit))' })}
            {stat('24', 'Days saved', { left: 'var(--space-200)', top: 'calc(46 * var(--proto-unit))' })}
            {stat('$120K', 'Budget saved', { right: 'var(--space-200)', top: 'calc(46 * var(--proto-unit))' })}
            <div style={{ position: 'absolute', left: 0, right: 0, top: 'var(--proto-gauge-label)', textAlign: 'center' }}>
              <div className="t-heading-h2-medium">1 Year</div><div className="t-body-m-regular muted">Time horizon</div>
            </div>
          </NDS>
          <ContentCard title="Milestone" description="9 days left" bottom={<Stack gap="300" style={{ width: '100%' }}>
            <ProgressBar value={8} label="Milestone progress" />
            <div className="t-body-m-regular sec row" style={{ justifyContent: 'space-between' }}><span>Drafts</span><span>Re-submit</span><span>SG2 window</span><span>Gate</span></div>
            <Calendar defaultMonth={STORY_DATE} today={STORY_DATE} events={evByDay} value={day} onChange={setDay} />
            <Button type="secondary" size="m" iconLeft="system-plus" onClick={() => setAddOpen(true)}>Add event</Button>
            <NDS label="Calendar legend" className="row" style={{ gap: 'var(--space-400)', flexWrap: 'wrap' }}>
              {Object.values(EVENT_TYPES).map(t => <LegendSwatch key={t.label} label={t.label} color={TONE_COLOR[t.tone]} />)}
            </NDS>
          </Stack>} />
        </div>
      </div></div>

      <AddEventModal by={P.initials} open={addOpen} onClose={() => setAddOpen(false)} onAdd={e => {
        setEvents(ev => [...ev, e]); setAddOpen(false);
        toast({ title: 'Event created', primaryAction: { label: 'Undo', iconLeft: 'arrow-back-up', onClick: () => setEvents(ev => ev.filter(x => JSON.stringify(x) !== JSON.stringify(e))) }, duration: 5000 }); }} />
      <Drawer open={!!day} onOpenChange={o => !o && setDay(null)} title={day ? day.toLocaleDateString('en-US', { month: 'long', day: 'numeric', year: 'numeric' }) : ''} collapsible={false} overlay="none">{/* DS 2.0 bug: scrim above drawer */}
        <Stack gap="stack" style={{ padding: '0 var(--space-inset) var(--space-inset)' }}>
          {!dayEvents.length && <EmptyState cause="empty-container" size="section" heading="No Events on This Day" body="Add a private event for this day." />}
          {dayEvents.map((e, k) => (
            <ContentCard key={k} size="s" title={e.name || EVENT_TYPES[e.type].label} description={`${EVENT_TYPES[e.type].label} · ${e.time} · ${e.lasts}`}
              bottom={<Stack gap="200" style={{ width: '100%' }}>
                <span className="row t-body-m-regular sec" style={{ gap: 'var(--space-150)' }}>Created by <Avatar initials={PEOPLE[e.by].initials} type={PEOPLE[e.by].type} size="xs" /> {short(e.by)}</span>
                <div style={{ display: 'grid', gridTemplateColumns: '1fr 1fr', gap: 'var(--space-200)' }}>
                  {e.type === 'private' && <Button type="secondary" size="s" iconLeft="system-trash-delete" onClick={() => setEvents(ev => ev.filter(x => JSON.stringify(x) !== JSON.stringify(e)))}>Remove</Button>}
                  {e.type === 'private' && <Button type="tertiary" size="s" iconLeft="system-edit-rename" onClick={() => toast({ title: 'Edit event isn’t part of this flow' })}>Edit</Button>}
                </div>
              </Stack>} />))}
        </Stack>
      </Drawer>
    </AppShell>
  );
}

function AddEventModal({ by, open, onClose, onAdd }) {
  const [name, setName] = useState(''), [date, setDate] = useState(null), [time, setTime] = useState(''), [lasts, setLasts] = useState('1 day');
  useEffect(() => { if (open) { setName(''); setDate(null); setTime(''); setLasts('1 day'); } }, [open]);
  const [tried, setTried] = useState(false);
  useEffect(() => { if (open) setTried(false); }, [open]);
  const ok = name.trim() && date && time;
  return (
    <Modal open={open} onOpenChange={o => !o && onClose()} title="New Private Event" width="var(--overlay-width-m)"
      secondaryAction={{ label: 'Cancel', onClick: onClose }}
      primaryAction={{ label: 'Add event', onClick: () => ok ? onAdd({ date: iso(date), type: 'private', time, lasts, by, name }) : setTried(true) }}>
      <Stack gap="300">
        <TextField size="m" label="Event name" placeholder="Enter a name" value={name} onChange={setName} error={tried && !name.trim() ? 'Name is required' : undefined} />
        <div style={{ display: 'grid', gridTemplateColumns: '1fr 1fr', gap: 'var(--space-200)' }}>
          <Stack gap="150"><span className="t-label-m-medium">Date</span>
            <DatePicker size="m" placeholder="Select a date" value={date} onChange={setDate} today={STORY_DATE} format={d => d.toLocaleDateString('en-US', { month: 'short', day: 'numeric', year: 'numeric' })} /></Stack>
          <Stack gap="150"><span className="t-label-m-medium">Time</span>
            <TextField size="m" type="time" iconLeft="system-clock-time" placeholder="Select a time" value={time} onChange={setTime} error={tried && !time ? 'Select a time' : undefined} /></Stack>
        </div>
        <span className="t-label-m-medium">Lasts</span>
        <Inline gap="150" align="center">{['1 day', '2 days', '3 days', 'Custom'].map(l => <Chip key={l} selected={lasts === l} onChange={() => setLasts(l)}>{l}</Chip>)}</Inline>
        <span className="t-body-m-regular muted">Only you see this event. The team timeline is set by your admin and shown to everyone.</span>
      </Stack>
    </Modal>
  );
}
